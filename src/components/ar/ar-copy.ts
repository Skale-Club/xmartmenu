/**
 * Guest-facing text for the dish AR button, in the public menu languages
 * (menu-i18n.ts). Kept apart from MenuCopy so the AR module stays
 * self-contained; unknown languages fall back to English.
 */

export interface ArCopy {
  /** Button on the dish photo that opens the camera with the dish on the guest's table. */
  viewOnTable: string
  /** Screen-reader name of the small cube on a dish card: this dish has a 3D model. */
  available: string
  /** On a phone without an AR camera (no Google Play Services for AR, in-app browser). */
  arUnavailable: string
  /** iPhone, old model without its iOS file: shown while it is prepared. */
  preparing: string
  // Inside the camera (Android, src/components/ar/WebXrDishViewer.tsx).
  /** Before a surface is found. */
  scanning: string
  /** A surface was found: tap to place the item there (generic: may be a dish, drink or dessert). */
  tapToPlace: string
  /** After placing: what the fingers do (no resizing: the dish stays at its real size). */
  gestures: string
  /** First-time hint after the dish lands (once per browser). */
  dragToMove: string
  /** Tips while no table is found, one at a time after a few seconds. */
  hintLight: string
  hintTexture: string
  hintStepBack: string
  /** A placed dish lost its table. */
  trackingLost: string
  /** Bag button in the top bar (with the item count). */
  viewOrder: string
  /** Order sheet: title, total row, leave AR for the menu cart, close the sheet. */
  yourOrder: string
  total: string
  goToCart: string
  keepBrowsing: string
  /** Details sheet: the row with this dish's line total and the stepper. */
  inYourOrder: string
  /** "i" button / details sheet title, and its ingredients heading. */
  details: string
  /** Details sheet: leaves the camera and opens the dish's own screen. */
  moreInfo: string
  ingredients: string
  /** Order sheet: unit price under a line with more than one; {price} = the unit price. */
  each: string
  /** Loading card while a dish's 3D model downloads. */
  loadingModel: string
  justAMoment: string
  /** Carousel chevrons on the name strip. */
  prevDish: string
  nextDish: string
  /** Stepper "−". */
  removeOne: string
  /** Closes a sheet back to the camera. */
  back: string
  /** "Real size" label. */
  realSize: string
  /** Shown with the lost-table notice: back to finding the table. */
  tryAgain: string
  addToOrder: string
  /** The dish needs a choice (size, flavour…) first: leaves the camera. */
  chooseOptions: string
  /** Toast after adding; {count} = items in the order. */
  added: string
  close: string
  /** "?" button: shows the gestures again. */
  help: string
  // Computers (no AR camera): the dish sheet's 3D viewer.
  /** Button that swaps the dish photo for the 3D model. */
  view3d: string
  /** Button that brings the photo back. */
  viewPhoto: string
  /** Over the 3D model: mouse controls. */
  turnHint: string
}

