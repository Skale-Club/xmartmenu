import { optimizeImageToWebP } from './media/optimize-image'
import { IMAGE_PROFILES, imagePolicy, type ImageOptimizationOptions } from './media/image-policy'

// The browser shrinks photos before sending (src/lib/media/client-compress.ts);
// this is the ceiling for whatever still arrives large.
export const MAX_FILE_SIZE = 15 * 1024 * 1024 // 15MB
export const WEBP_QUALITY = 80
export const MAX_IMAGE_DIMENSION = IMAGE_PROFILES.photo.maxSide

export async function validateAndConvertToWebP(file: File, options: ImageOptimizationOptions = {}): Promise<{ buffer: Buffer; contentType: string; extension: string; error?: never } | { buffer?: never; error: string }> {
  if (file.size > MAX_FILE_SIZE) {
    return { error: `File is too large. Maximum allowed size is 15MB (received: ${(file.size / 1024 / 1024).toFixed(1)}MB)` }
  }

  const allowed = ['image/jpeg', 'image/jpg', 'image/png', 'image/webp', 'image/gif', 'image/avif', 'image/svg+xml']
  if (!allowed.includes(file.type)) {
    return { error: 'Unsupported format. Use PNG, JPG, WebP, AVIF or GIF.' }
  }

  const bytes = await file.arrayBuffer()
  const input = Buffer.from(bytes)

  // SVG is not converted to WebP; serve it directly.
  if (file.type === 'image/svg+xml') {
    if (input.length > imagePolicy(options).maxBytes) {
      return { error: 'SVG is too large. Simplify the vector image before uploading.' }
    }
    return { buffer: input, contentType: 'image/svg+xml', extension: 'svg' }
  }

  // GIFs keep their animation; everything is turned upright from its EXIF
  // orientation (phone photos otherwise land sideways) and stripped of metadata.
  try {
    const buffer = await optimizeImageToWebP(input, options)
    return { buffer, contentType: 'image/webp', extension: 'webp' }
  } catch {
    return { error: 'Image could not be optimized. Try a smaller image or a shorter animation.' }
  }
}

/**
 * Converts generated images and video posters with the same byte budget as uploads.
 * Sibling to validateAndConvertToWebP; accepts Buffer input (for AI-generated bytes).
 * Used by Phase 10 image seeding routes. Sharp is already the installed converter.
 */
export async function convertBufferToWebP(input: Buffer, options: ImageOptimizationOptions = {}): Promise<Buffer> {
  return optimizeImageToWebP(input, options)
}
